            f"🔭 מה צפוי לתלמיד בהמשך המסלול (היעד הבא באופק):\n"
            f"• {next_preview}\n\n"
            f"📋 בקשת התלמיד ממך כמנטור (אנא ספק תשובה ברורה בעברית):\n"
