# -*- coding: utf-8 -*-

class Lesson:
    def __init__(self, id, chapter, title, recap, why_learn, when_to_use, explanation, tip, default_code, expected_output, hint, success_message):
        self.id = id
        self.chapter = chapter
        self.title = title
        self.recap = recap
        self.why_learn = why_learn
        self.when_to_use = when_to_use
        self.explanation = explanation
        self.tip = tip
        self.default_code = default_code
        self.expected_output = expected_output.strip()
        self.hint = hint
        self.success_message = success_message

    def get_gemini_prompt(self):
        total_lessons = len(LESSONS) if 'LESSONS' in globals() else 25
        percent = round((self.id / total_lessons) * 100)

        # פירוט הידע שנרכש עד כה
        if self.id == 1:
            known_skills = "• התלמיד בנקודת ההתחלה המוחלטת (שיעור ראשון במסלול, ללא כל ידע קודם בתכנות או בפייתון)."
        else:
            previous_lessons = LESSONS[:self.id - 1]
            known_skills = "\n".join([
                f"• שלב {l.id} ({l.chapter}): {l.title.split(':')[-1].strip()} - {l.when_to_use.split('.')[0]}."
                for l in previous_lessons
            ])

        # מה צפוי לתלמיד בהמשך המסלול
        if self.id < total_lessons:
            next_l = LESSONS[self.id]
            next_preview = f"בשלב הבא (שלב {next_l.id} - {next_l.title}): נלמד {next_l.why_learn}"
            if self.id + 1 < total_lessons:
                future_l = LESSONS[self.id + 1]
                next_preview += f"\n• ובהמשך (שלב {future_l.id}): {future_l.title}"
        else:
            next_preview = "זהו שלב השיא והסיום של הקורס! התלמיד מוכן כעת לפרויקטים עצמאיים ולפיתוח יישומים מלאים בעולם האמיתי."

