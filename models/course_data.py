            f"📍 תמונת המצב המלאה של התלמיד כרגע:\n"
            f"• שלב נוכחי: שלב {self.id} מתוך {total_lessons} ({self.chapter} - {self.title})\n"
            f"• התקדמות במסלול: {percent}% מהקורס הושלמו.\n\n"
            f"🧠 מה התלמיד כבר יודע ושולט בו עד כה:\n"
            f"{known_skills}\n\n"
            f"⚠️ הנחיה פדגוגית קריטית: התאם את ההסבר והדוגמאות שלך אך ורק לכלים שהתלמיד כבר מכיר לפי רשימת הידע שנרכש למעלה + הנושא הנוכחי! אין להשתמש במושגים שלא נלמדו עדיין במסלול.\n\n"
            f"🎯 הנושא הנלמד כרגע:\n"
            f"• נושא: {self.title}\n"
            f"• למה לומדים את זה עכשיו: {self.why_learn}\n"
            f"• מתי ואיך נשתמש בזה בעולם האמיתי: {self.when_to_use}\n"
            f"• הקוד שעליו התלמיד מתרגל כעת:\n"
